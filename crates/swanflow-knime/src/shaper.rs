//! Shaper SQL Generator
//!
//! Converts mapped KNIME visualization nodes into Shaper-compatible SQL
//! with type annotations (e.g., `::BARCHART_XAXIS`, `::BARCHART`).
//!
//! Pipeline:
//!   1. Find all visualization nodes in the workflow
//!   2. Trace upstream through edges to locate the data source
//!   3. Extract column info from the data source
//!   4. Generate annotated SQL

use crate::types::{KnimeEdge, KnimeNode, KnwfArchive};
use serde_json::Value;
use std::collections::{HashMap, HashSet, VecDeque};

/// A single Shaper dashboard query.
#[derive(Debug, Clone)]
pub struct ShaperQuery {
    /// Which visualization node produced this
    pub node_name: String,
    /// Shaper chart type (BARCHART, LINE, PIE, …)
    pub chart_type: String,
    /// The generated SQL query with ::ANNOTATION suffixes
    pub sql: String,
    /// Data source description
    pub source: String,
}

/// Result of tracing upstream from a node.
#[derive(Debug, Clone)]
struct UpstreamTrace {
    /// The data-source node (CSV Reader, DB Reader, …)
    source_node: KnimeNode,
    /// Intermediate transform nodes in order (nearest first)
    pipeline: Vec<KnimeNode>,
}

/// Known data-source node name prefixes.
const DATA_SOURCE_NAMES: &[&str] = &[
    "CSV Reader", "Excel Reader", "Table Reader", "Parquet Reader",
    "File Reader", "DB Reader", "MySQL Connector", "DuckDB Reader",
    "Database Reader", "Table Creator", "Create Table",
];

// (shaper-specific helpers — see mapper.rs for chart-type resolution)

// ─── Public API ──────────────────────────────────────────────────────

/// Generate Shaper SQL queries for all visualization nodes in a workflow.
pub fn generate_shaper_queries(archive: &KnwfArchive) -> Vec<ShaperQuery> {
    let reverse_edges = build_reverse_edges(&archive.edges);
    let node_map: HashMap<&str, &KnimeNode> =
        archive.nodes.iter().map(|n| (n.id.as_str(), n)).collect();

    let mut queries = Vec::new();

    for node in &archive.nodes {
        let name = node.name.as_deref().unwrap_or("");
        let clean_name = strip_suffix(name);

        // Is this a visualization node?
        let chart_type = match resolve_chart_type(clean_name) {
            Some(ct) => ct,
            None => continue,
        };

        // Trace upstream to find the data source
        let trace = trace_upstream(
            &node.id, &reverse_edges, &node_map, 10,
        );

        let sql = match &trace {
            Some(t) => build_shaper_sql(t, chart_type),
            None => {
                // No data source found — generate placeholder
                format!(
                    "-- Shaper: {} → {}\n-- No upstream data source found. Wire a data reader to this node.\nSELECT 'no_data'::{} AS placeholder",
                    name, chart_type, suffix_annotation(chart_type, "value"),
                )
            }
        };

        queries.push(ShaperQuery {
            node_name: name.to_string(),
            chart_type: chart_type.to_string(),
            sql,
            source: trace
                .as_ref()
                .map(|t| t.source_node.name.clone().unwrap_or_default())
                .unwrap_or_else(|| "unknown".into()),
        });
    }

    queries
}

/// Write all Shaper queries to a .sql file that Shaper can ingest.
pub fn write_shaper_sql(archive: &KnwfArchive, output_path: &str) -> std::io::Result<()> {
    let queries = generate_shaper_queries(archive);
    let mut sql = String::new();

    sql.push_str("-- Generated by SwanFlow KNIME → Shaper\n");
    sql.push_str(&format!(
        "-- {} visualization queries\n\n",
        queries.len()
    ));

    for q in &queries {
        sql.push_str(&format!("-- [{}] {}\n", q.chart_type, q.node_name));
        sql.push_str(&q.sql);
        sql.push_str(";\n\n");
    }

    std::fs::write(output_path, sql)?;
    Ok(())
}

// ─── Upstream Tracing ────────────────────────────────────────────────

/// Build reverse adjacency: target_id → [(source_id, source_port, target_port)]
fn build_reverse_edges(edges: &[KnimeEdge]) -> HashMap<&str, Vec<&KnimeEdge>> {
    let mut rev: HashMap<&str, Vec<&KnimeEdge>> = HashMap::new();
    for e in edges {
        rev.entry(e.target_id.as_str()).or_default().push(e);
    }
    rev
}

/// BFS upstream from `start_id` to find the nearest data-source node.
fn trace_upstream<'a>(
    start_id: &str,
    reverse_edges: &HashMap<&str, Vec<&'a KnimeEdge>>,
    node_map: &HashMap<&str, &'a KnimeNode>,
    max_depth: usize,
) -> Option<UpstreamTrace> {
    let mut visited: HashSet<&str> = HashSet::new();
    let mut queue: VecDeque<(String, Vec<String>, usize)> = VecDeque::new();

    queue.push_back((start_id.to_string(), vec![], 0));
    visited.insert(start_id);

    while let Some((current_id, path, depth)) = queue.pop_front() {
        if depth > max_depth {
            continue;
        }

        let current = node_map.get(current_id.as_str())?;
        let name = current.name.as_deref().unwrap_or("");

        // Check if this node is a data source
        if depth > 0 && is_data_source(name) {
            let pipeline: Vec<KnimeNode> = path
                .iter()
                .filter_map(|id| node_map.get(id.as_str()).cloned().cloned())
                .collect();
            return Some(UpstreamTrace {
                source_node: (*current).clone(),
                pipeline,
            });
        }

        // Continue BFS upstream
        if let Some(incoming) = reverse_edges.get(current_id.as_str()) {
            for edge in incoming {
                if !visited.contains(edge.source_id.as_str()) {
                    let mut new_path = path.clone();
                    new_path.push(current_id.clone());
                    visited.insert(edge.source_id.as_str());
                    queue.push_back((
                        edge.source_id.clone(),
                        new_path,
                        depth + 1,
                    ));
                }
            }
        }
    }

    None
}

// ─── SQL Generation ──────────────────────────────────────────────────

/// Build a Shaper-annotated SQL query from an upstream trace.
fn build_shaper_sql(trace: &UpstreamTrace, chart_type: &str) -> String {
    let source_name = trace.source_node.name.as_deref().unwrap_or("");
    let clean_source = strip_suffix(source_name);

    // Extract columns from the data source's settings
    let columns = extract_columns(&trace.source_node.settings);

    if columns.is_empty() {
        return format!(
            "-- Shaper: {}\n-- Source: {} (no column info available)\nSELECT 1::{}",
            chart_type, clean_source, suffix_annotation(chart_type, "dummy"),
        );
    }

    // Heuristic: pick first string/int column for X axis, first numeric for Y
    let (x_col, y_col) = pick_axes(&columns, chart_type);

    match chart_type {
        "TABLE" => {
            let cols: Vec<String> = columns.iter().map(|c| c.name.clone()).collect();
            format!("SELECT {} FROM '{}'", cols.join(", "), source_path(&trace.source_node.settings))
        }
        "PIECHART" | "BARCHART" | "LINECHART" | "SCATTERPLOT" | "BUBBLECHART" => {
            // Most charts need X axis (category) + Y axis (value)
            let x_suffix = suffix_annotation(chart_type, "xaxis");
            let y_suffix = suffix_annotation(chart_type, "value");

            let x_expr = format!(
                "{}::{},\n  {}::{}",
                x_col, x_suffix,
                y_col, y_suffix,
            );

            let source = source_path(&trace.source_node.settings);

            // If there are intermediate GroupBy/Aggregation nodes, we'd
            // ideally trace through them. For now, add a GROUP BY hint.
            let has_agg = trace.pipeline.iter().any(|n| {
                let name = n.name.as_deref().unwrap_or("").to_lowercase();
                name.contains("group") || name.contains("agg")
            });

            if has_agg {
                format!(
                    "SELECT {}\nFROM '{}'\nGROUP BY {}",
                    x_expr, source, x_col,
                )
            } else {
                format!(
                    "SELECT {}::XAXIS,\n  COUNT(*)::{}\nFROM '{}'\nGROUP BY {}",
                    x_col, chart_type, source, x_col,
                )
            }
        }
        "HEATMAP" => {
            // Heatmap needs X, Y, and value
            let third = if columns.len() > 2 {
                columns[2].name.clone()
            } else {
                "COUNT(*)".to_string()
            };
            format!(
                "SELECT {}::HEATMAP_XAXIS,\n  {}::HEATMAP_YAXIS,\n  {}::HEATMAP\nFROM '{}'\nGROUP BY {}, {}",
                x_col, y_col, third,
                source_path(&trace.source_node.settings),
                x_col, y_col,
            )
        }
        "SUNBURST" => {
            // Sunburst: hierarchical categories
            let path_cols: Vec<&str> = columns.iter().take(3).map(|c| c.name.as_str()).collect();
            let path_str = path_cols.join(", ");
            format!(
                "SELECT {}::SUNBURST,\n  COUNT(*)::SUNBURST_VALUE\nFROM '{}'\nGROUP BY {}",
                path_str,
                source_path(&trace.source_node.settings),
                path_str,
            )
        }
        "PARALLEL" => {
            // Parallel coordinates: multiple numeric columns
            let num_cols: Vec<&str> = columns
                .iter()
                .filter(|c| c.is_numeric())
                .map(|c| c.name.as_str())
                .collect();
            let expr: Vec<String> = num_cols
                .iter()
                .map(|c| format!("{}::PARALLEL", c))
                .collect();
            format!(
                "SELECT {}\nFROM '{}'",
                expr.join(",\n  "),
                source_path(&trace.source_node.settings),
            )
        }
        _ => {
            // Generic fallback
            format!(
                "SELECT {}::{},\n  {}::{}\nFROM '{}'\nGROUP BY {}",
                x_col, suffix_annotation(chart_type, "xaxis"),
                y_col, suffix_annotation(chart_type, "value"),
                source_path(&trace.source_node.settings),
                x_col,
            )
        }
    }
}

// ─── Helpers ─────────────────────────────────────────────────────────

/// Column info extracted from a KNIME node's settings.xml.
#[derive(Debug, Clone)]
struct ColumnInfo {
    name: String,
    java_type: String,
}

impl ColumnInfo {
    fn is_numeric(&self) -> bool {
        self.java_type.contains("Double")
            || self.java_type.contains("Integer")
            || self.java_type.contains("Long")
            || self.java_type.contains("Float")
            || self.java_type.contains("Number")
    }
}

/// Extract column names and types from a node's settings Value.
///
/// With the stack-based parser, settings have a nested structure like:
///   settings["settings.xml"]["model"]["table_spec_config_Internals"]...
/// or just:
///   settings["model"]["table_spec_config_Internals"]...  (legacy flat format)
fn extract_columns(settings: &Value) -> Vec<ColumnInfo> {
    // Find the `model` object — may be wrapped in root config key
    let model = find_model(settings);
    let model = match model {
        Some(m) => m,
        None => return vec![],
    };

    let spec_config = match model.get("table_spec_config_Internals") {
        Some(v) => v,
        None => return vec![],
    };

    let specs = match spec_config.get("individual_specs") {
        Some(v) => v,
        None => return vec![],
    };

    for (_path, file_spec) in specs.as_object().unwrap_or(&Default::default()) {
        let mut cols = Vec::new();
        for i in 0.. {
            let key = i.to_string();
            let col = match file_spec.get(&key) {
                Some(v) => v,
                None => break,
            };
            let name = col
                .get("name")
                .and_then(|v| v.as_str())
                .unwrap_or("?")
                .to_string();
            let java_type = col
                .get("type")
                .and_then(|t| t.get("class"))
                .and_then(|v| v.as_str())
                .unwrap_or("java.lang.String")
                .to_string();
            cols.push(ColumnInfo { name, java_type });
        }
        if !cols.is_empty() {
            return cols;
        }
    }

    vec![]
}

/// Find the `model` config in settings JSON. Handles both:
/// - New format: `{"settings.xml": {"model": {...}, ...}}`
/// - Legacy flat: `{"model": {...}}`  
fn find_model(settings: &Value) -> Option<&Value> {
    // Direct model (legacy flat format)
    if let Some(model) = settings.get("model") {
        return Some(model);
    }
    // Root-wrapped: find first config key that contains "model"
    if let Some(obj) = settings.as_object() {
        for (_root_key, root_val) in obj {
            if let Some(model) = root_val.get("model") {
                return Some(model);
            }
        }
    }
    None
}

/// Extract the data file path from a source node's settings.
fn source_path(settings: &Value) -> String {
    let model = find_model(settings);

    // Try KNIME Relative-to-workflow-data path
    if let Some(path) = model
        .and_then(|m| m.get("table_spec_config_Internals"))
        .and_then(|t| t.get("source_group_id"))
        .and_then(|v| v.as_str())
    {
        let filename = path.rsplit('/').next().unwrap_or(path);
        return filename.to_string();
    }

    // Try direct file_selection path
    if let Some(path) = model
        .and_then(|m| m.get("settings"))
        .and_then(|s| s.get("file_selection"))
        .and_then(|f| f.get("path"))
        .and_then(|p| p.get("path"))
        .and_then(|v| v.as_str())
    {
        let filename = path.rsplit('/').next().unwrap_or(path);
        return filename.to_string();
    }

    "data.csv".to_string()
}
fn pick_axes(columns: &[ColumnInfo], _chart_type: &str) -> (String, String) {
    // X: first non-numeric (category) column, or first column if all numeric
    let x = columns
        .iter()
        .find(|c| !c.is_numeric())
        .unwrap_or(&columns[0])
        .name
        .clone();

    // Y: first numeric column
    let y = columns
        .iter()
        .find(|c| c.is_numeric())
        .unwrap_or(&columns[0])
        .name
        .clone();

    (x, y)
}

/// Map KNIME chart name to Shaper annotation suffix.
/// Only types confirmed in Shaper's SQL reference:
/// https://taleshape.com/shaper/docs/dashboard-sql-reference/
fn resolve_chart_type(name: &str) -> Option<&'static str> {
    for &(knime_name, shaper_type) in &[
        ("Bar Chart", "BARCHART"),
        ("Line Plot", "LINECHART"),
        ("Pie Chart", "PIECHART"),
        ("Scatter Plot", "SCATTERPLOT"),
        ("Scatter Plot Matrix", "SCATTERPLOT"),
        ("Histogram", "BARCHART"),       // Shaper has no HISTOGRAM type
        ("Heatmap", "HEATMAP"),
        ("Box Plot", "LINECHART"),        // Shaper has no BOXPLOT type
        ("Stacked Area Chart", "BARCHART"), // Shaper has no AREACHART
        ("Sunburst Chart", "SUNBURST"),
        ("Density Plot", "LINECHART"),    // Shaper has no DENSITYPLOT type
        ("2D Density Plot", "LINECHART"),
        ("Table View", "TABLE"),
        ("Tile View", "TABLE"),
        ("Table Editor", "TABLE"),
        ("Generic ECharts View", "ECHART"),
        ("Generic JavaScript View", "ECHART"),
        ("Parallel Coordinates Plot", "PARALLEL"),
        ("Bubble Chart", "BUBBLECHART"),
        ("Radar Plot", "SCATTERPLOT"),    // Shaper has no RADAR type
        ("Radar Plot Appender", "SCATTERPLOT"),
        ("Violin Plot", "BARCHART"),      // Shaper has no VIOLINPLOT
        ("Contour Plot", "HEATMAP"),
        ("Error Bars Plot", "SCATTERPLOT"),
        ("Tag Cloud", "TABLE"),
        ("Spark Line Appender", "LINECHART"),
    ] {
        if name == knime_name {
            return Some(shaper_type);
        }
    }
    None
}

/// Generate the correct Shaper annotation suffix for an axis.
///
/// Shaper uses DuckDB custom types:
///   - `col::XAXIS` → X axis (for bar, line, box, scatter, area, histogram)
///   - `col::YAXIS` → Y axis
///   - `col::BARCHART` → bar chart value column
///   - `col::LINECHART` → line chart value column
///   - `col::PIECHART` → pie chart value column
///   - `col::BARCHART_STACKED` → stacked bar
///   - `col::CATEGORY` → category grouping
///   - `col::COLOR` → color grouping
///
///   See: https://taleshape.com/shaper/docs/dashboard-sql-reference/
fn suffix_annotation(chart_type: &str, axis: &str) -> String {
    match (chart_type, axis) {
        (_, "xaxis") => "XAXIS".to_string(),
        (_, "yaxis") => "YAXIS".to_string(),
        (_, "value") => chart_type.to_string(),
        (_, "category") => "CATEGORY".to_string(),
        (_, "color") => "COLOR".to_string(),
        _ => chart_type.to_string(),
    }
}

fn strip_suffix(name: &str) -> &str {
    name.split(" (#").next().unwrap_or(name).trim()
}

fn is_data_source(name: &str) -> bool {
    let clean = strip_suffix(name);
    DATA_SOURCE_NAMES
        .iter()
        .any(|ds| clean.starts_with(ds))
}

